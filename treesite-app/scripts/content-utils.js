import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";

export const appRoot = process.cwd();
export const contentItemsDir = path.join(appRoot, "content", "items");
export const generatedContentPath = path.join(appRoot, "src", "generatedContentItems.js");
export const supportedContentTypes = [
  "text",
  "link",
  "href",
  "contact",
  "pdf",
  "website",
  "htmlCard",
  "section"
];

export function parseArgs(argv = process.argv.slice(2)) {
  const args = {};

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (!arg.startsWith("--")) {
      throw new Error(`Unexpected argument: ${arg}`);
    }

    const [rawKey, inlineValue] = arg.slice(2).split("=", 2);
    const key = rawKey.trim();
    if (!key) {
      throw new Error(`Invalid argument: ${arg}`);
    }

    if (inlineValue !== undefined) {
      args[key] = inlineValue;
      continue;
    }

    const next = argv[i + 1];
    if (!next || next.startsWith("--")) {
      args[key] = true;
      continue;
    }

    args[key] = next;
    i += 1;
  }

  return args;
}

export function requireArg(args, name) {
  const value = args[name];
  if (typeof value !== "string" || value.trim() === "") {
    throw new Error(`Missing required --${name} value.`);
  }

  return value.trim();
}

export function slugify(value) {
  return value
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

export function parseValue(value, fallback = 8) {
  if (value === undefined) return fallback;

  const parsed = Number(value);
  if (!Number.isFinite(parsed) || parsed <= 0) {
    throw new Error("--value must be a positive number.");
  }

  return parsed;
}

export function publicPath(...parts) {
  return `/${["assets", ...parts].join("/")}`;
}

export function contentItemPath(slug) {
  return path.join(contentItemsDir, `${slug}.json`);
}

export async function writeContentItem(slug, item) {
  await fs.mkdir(contentItemsDir, { recursive: true });

  const itemPath = contentItemPath(slug);
  await fs.writeFile(itemPath, `${JSON.stringify(item, null, 2)}\n`);

  return itemPath;
}

export async function readContentItem(slug) {
  const itemPath = contentItemPath(slug);
  const source = await fs.readFile(itemPath, "utf8");
  const item = JSON.parse(source);
  item.slug ||= slug;
  validateContentItem(item, `${slug}.json`);
  return item;
}

export async function readContentItems() {
  await fs.mkdir(contentItemsDir, { recursive: true });

  const entries = await fs.readdir(contentItemsDir, { withFileTypes: true });
  const items = [];

  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith(".json")) continue;

    const itemPath = path.join(contentItemsDir, entry.name);
    const source = await fs.readFile(itemPath, "utf8");
    const item = JSON.parse(source);
    item.slug ||= path.basename(entry.name, ".json");
    validateContentItem(item, entry.name);
    items.push(item);
  }

  return items.sort((a, b) => {
    const sectionOrder = a.section.localeCompare(b.section);
    if (sectionOrder !== 0) return sectionOrder;
    return a.name.localeCompare(b.name);
  });
}

export function validateContentItem(item, filename = "item") {
  for (const field of ["name", "section", "type", "slug"]) {
    if (typeof item[field] !== "string" || item[field].trim() === "") {
      throw new Error(`${filename} must include a non-empty "${field}" field.`);
    }
  }

  if (!supportedContentTypes.includes(item.type)) {
    throw new Error(`${filename} has unsupported type "${item.type}".`);
  }

  if (item.type === "pdf" && typeof (item.pdf || item.source) !== "string") {
    throw new Error(`${filename} pdf items must include "pdf" or "source".`);
  }

  if (item.type === "website" && typeof (item.url || item.source) !== "string") {
    throw new Error(`${filename} website items must include "url" or "source".`);
  }

  if (item.type === "htmlCard" && typeof (item.source || item.html) !== "string") {
    throw new Error(`${filename} htmlCard items must include "source" or "html".`);
  }

  if (item.type === "section") {
    if (item.color !== undefined && typeof item.color !== "string") {
      throw new Error(`${filename} section color must be a string when provided.`);
    }
  }

  if (["link", "href"].includes(item.type) && typeof (item.href || item.url || item.source) !== "string") {
    throw new Error(`${filename} ${item.type} items must include "href", "url", or "source".`);
  }

  if (item.hidden !== undefined && typeof item.hidden !== "boolean") {
    throw new Error(`${filename} hidden must be a boolean when provided.`);
  }
}

export async function rebuildGeneratedContent() {
  const items = await readContentItems();
  const source = [
    "// Generated by scripts/rebuild-site-data.js. Do not hand-edit.",
    `export const generatedContentItems = ${JSON.stringify(items, null, 2)};`,
    ""
  ].join("\n");

  await fs.writeFile(generatedContentPath, source);
  return items.length;
}
